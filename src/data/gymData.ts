// Gap curriculum skills mapped from review table & USAG gaps
export const GAP_CURRICULUM_SKILLS: Skill[] = USAG_GAP_SKILLS;

const reviewMapByName = new Map(
  SKILLS_GAP_REVIEW_DATA.map((r) => [r.name.toLowerCase().trim(), r])
);

// Master curriculum combining authentic Gymfest Document skills with USAG 4-event gaps
const ALL_CANDIDATE_SKILLS: Skill[] = [
  // 1. Authentic Gymfest Document Foundation (Pre-Level through Level 2)
  ...GYMFEST_DOCUMENT_SKILLS.map((s) => {
    const match = reviewMapByName.get(s.name.toLowerCase().trim());
    return {
      ...s,
      writtenTutorial: match?.writtenTutorial || s.writtenTutorial,
      tutorial: match?.videoTutorial || s.tutorial,
      officialRef: match?.elementCode || s.officialRef,
    };
  }),

  // 2. Authentic Gymfest Document Advanced (Levels 3 through 8 across Silver, Gold, Platinum)
  ...GYMFEST_ADVANCED_SKILLS.map((s) => {
    const match = reviewMapByName.get(s.name.toLowerCase().trim());
    return {
      ...s,
      writtenTutorial: match?.writtenTutorial || s.writtenTutorial,
      tutorial: match?.videoTutorial || s.tutorial,
      officialRef: match?.elementCode || s.officialRef,
    };
  }),

  // 3. USAG Gaps across Uneven Bars, Balance Beam, Vault, and Floor Exercise
  ...USAG_GAP_SKILLS.map((s) => {
    const match = reviewMapByName.get(s.name.toLowerCase().trim());
    return {
      ...s,
      writtenTutorial: match?.writtenTutorial || s.writtenTutorial,
      tutorial: match?.videoTutorial || s.tutorial,
      officialRef: match?.elementCode || s.officialRef,
    };
  }),
];

// Clean deduplication by unique ID and unique Name+Level+Category
const seenSkillIds = new Set<string>();
const seenSkillKeys = new Set<string>();
const deduplicatedSkills: Skill[] = [];

for (const s of ALL_CANDIDATE_SKILLS) {
  const normName = s.name.toLowerCase().replace(/[^a-z0-9]/g, "");
  const key = `${s.level}_${s.category}_${normName}`;
  if (!seenSkillIds.has(s.id) && !seenSkillKeys.has(key)) {
    seenSkillIds.add(s.id);
    seenSkillKeys.add(key);
    deduplicatedSkills.push(s);
  }
}

